// ── Overview Builder ─────────────────────────────────────────────────────────

export function buildOverviewData(): OverviewData {
  const healthy = servicesData.filter((s) => s.status === 'healthy').length;
  const degraded = servicesData.filter((s) => s.status === 'degraded').length;
  const unhealthy = servicesData.filter((s) => s.status === 'unhealthy').length;

  const totalRps = servicesData.reduce((sum, s) => sum + s.requestRate, 0);
  const avgErrorRate =
    servicesData.reduce((sum, s) => sum + s.errorRate, 0) / servicesData.length;
  const maxP99 = Math.max(...servicesData.map((s) => s.latencyP99Ms));
  const avgP50 =
    servicesData.reduce((sum, s) => sum + s.latencyP50Ms, 0) / servicesData.length;

  const activeAlertsCount = alertsData.filter((a) => a.state === 'firing').length;
  const criticalAlertsCount = alertsData.filter((a) => a.state === 'firing' && a.severity === 'critical').length;
  const openIncidentsCount = incidentsData.filter((i) => i.state !== 'resolved').length;
  const sev1Count = incidentsData.filter((i) => i.state !== 'resolved' && i.severity === 'sev1').length;

  return {
    systemHealth: {
      overallStatus: unhealthy > 0 ? 'unhealthy' : degraded > 0 ? 'degraded' : 'healthy',
      healthyServices: healthy,
      degradedServices: degraded,
      unhealthyServices: unhealthy,
      totalServices: servicesData.length,
    },
    metrics: {
      requestRateRps: totalRps,
      requestRateChangePercent: 12.4,
      errorRatePercent: parseFloat(avgErrorRate.toFixed(2)),
      errorRateChangePercent: -0.4,
      latencyP50Ms: Math.round(avgP50),
      latencyP95Ms: 160,
      latencyP99Ms: maxP99,
      latencyChangePercent: 8.2,
    },
    telemetryTrends: {
      requestRateSeries: generateTimeSeries(24, totalRps, 600, 400),
      errorRateSeries: generateTimeSeries(24, avgErrorRate, 0.4, -0.1),
      latencyP99Series: generateTimeSeries(24, maxP99, 120, 80),
      latencyP50Series: generateTimeSeries(24, avgP50, 4, 1),
    },
    activeAlerts: activeAlertsCount,
    criticalAlerts: criticalAlertsCount,
    openIncidents: openIncidentsCount,
    activeSev1Incidents: sev1Count,
    slosAtRisk: slosData.filter((s) => s.status === 'at_risk').length,
    slosBreached: slosData.filter((s) => s.status === 'breached').length,
    recentAlerts: alertsData.slice(0, 5),
    recentIncidents: incidentsData.slice(0, 5),
    services: servicesData,
    slos: slosData,
    recentLogs: logsData.slice(0, 6),
    recentTraces: tracesData.slice(0, 4),
    generatedAt: new Date().toISOString(),
  };
}
