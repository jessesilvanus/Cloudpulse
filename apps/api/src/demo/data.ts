// ── Time-Series Generators ───────────────────────────────────────────────────

function generateTimeSeries(pointsCount: number, base: number, variance: number, trend = 0): MetricDatapoint[] {
  const points: MetricDatapoint[] = [];
  const intervalMs = (15 * 60 * 1000) / pointsCount; // last 15 mins
  const startTime = now.getTime() - 15 * 60 * 1000;

  for (let i = 0; i < pointsCount; i++) {
    const time = new Date(startTime + i * intervalMs).toISOString();
    const noise = (Math.sin(i / 2) + Math.cos(i / 3)) * variance;
    const trendVal = (i / pointsCount) * trend;
    const value = Math.max(0, Math.round((base + noise + trendVal) * 100) / 100);
    points.push({ timestamp: time, value });
  }
  return points;
}

